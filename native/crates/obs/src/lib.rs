//! slinky-obs: the network inputs of a game state, the egocentric board observation and the
//! mode features of every seat, bit-exact with slinky's jitted Python.
//!
//! Sources (the Python of slinky v0.1.0): `src/slinky/observations.py` (planes and window,
//! lines 51-125), `src/slinky/modes.py` (`mode_features` 124-158, `hide_food` 161-173),
//! `src/slinky/unified.py` (`policy_features` 260-274, `policy_inputs` 277-292) and
//! `baselines/az_modes.py` (`make_evaluator` 209-223). See `native-az/SPEC.md` section 3.
//!
//! Parity: `tests/golden.rs` compares the f32 bit patterns of every seat's board and feature row
//! against `jax.jit(unified.policy_inputs)` on states from random games in all four modes (plus
//! 3-snake, 2-snake royale and constrictor, a royale with a 7-turn shrink and 7x7 and 9x11
//! boards), generated by `native/golden/obs_golden.py`.
//!
//! # Public API
//!
//! ```
//! use slinky_obs::{Encoder, NUM_FEATURES, OBS_LEN};
//! use slinky_rules::{GameConfig, GameState, Mode};
//!
//! let cfg = GameConfig::for_mode(Mode::Duel, None)?;
//! let mut s = GameState::new(&cfg);
//! s.set_snake(&cfg, 0, &[(1, 1), (1, 1), (1, 1)], 100, None)?;
//! s.set_snake(&cfg, 1, &[(9, 9), (9, 9), (9, 9)], 100, None)?;
//!
//! // One encoder per game: told mode = cfg.mode(), food hidden iff the ruleset is constrictor
//! // and config.json's hide_constrictor_food is set.
//! let enc = Encoder::new(cfg, true);
//! let n = cfg.num_snakes();
//! let mut boards = vec![0.0f32; n * OBS_LEN];       // [N][21][21][13], NHWC
//! let mut feats = vec![0.0f32; n * NUM_FEATURES];   // [N][7]
//! enc.encode_into(&s, &mut boards, &mut feats)?;    // no allocation
//! assert_eq!(feats[1], 1.0);                         // is_duel
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! * [`Encoder`]: `new(GameConfig, hide_constrictor_food) -> Encoder`, `with_told_mode(Mode)`,
//!   `encode_into(&state, boards, feats) -> Result<usize, ObsError>` (all seats),
//!   `observe_into(&state, seat, out)` (one seat), `features(&state) -> [[f32; 7]; 4]`,
//!   `obs_len()`, `obs_shape()`, `config()`, `told_mode()`, `hides_food()`.
//! * Free functions: [`egocentric_into`]`(&state, &cfg, seat, hide_food, out)`,
//!   [`mode_features`]`(&state, &cfg, told) -> [[f32; 7]; 4]`, [`obs_shape`], [`obs_len`].
//! * Constants: [`NUM_CHANNELS`] = 13 (indices in [`ch`], names in [`CHANNEL_NAMES`]),
//!   [`NUM_FEATURES`] = 7 (indices in [`col`], names in [`FEATURE_NAMES`]), [`OBS_ROWS`] =
//!   [`OBS_COLS`] = 21 and [`OBS_LEN`] = 5,733 (the 11x11 window), [`TURN_SCALE`], [`RECIP_100`].
//!
//! Boards smaller than 11x11 give a smaller `(2H-1) x (2W-1)` window ([`obs_len`]); the
//! deployed networks take only 11x11.
//!
//! Speed (release, one core of the dev box, `examples/bench.rs`): about 0.7 us per seat, so 1.3 us
//! for a duel node and 3 us for a 4p node (the network forward is far slower).

mod encoder;
mod error;
mod features;
mod observation;

pub use encoder::Encoder;
pub use error::ObsError;
pub use features::{TURN_SCALE, col, mode_features};
pub use observation::{
    RECIP_100, SparseObs, egocentric_into, egocentric_sparse_into, obs_len, obs_shape,
};

use slinky_rules::{MAX_HEIGHT, MAX_WIDTH};

/// Observation planes (`observations.NUM_CHANNELS`, observations.py:30-46).
pub const NUM_CHANNELS: usize = 13;
/// Side features per seat (`modes.NUM_FEATURES`, modes.py:46-55).
pub const NUM_FEATURES: usize = 7;
/// Rows of the 11x11 egocentric window, `2H-1`.
pub const OBS_ROWS: usize = 2 * MAX_HEIGHT - 1;
/// Columns of the 11x11 egocentric window, `2W-1`.
pub const OBS_COLS: usize = 2 * MAX_WIDTH - 1;
/// Floats in one seat's 11x11 observation, `21 * 21 * 13`.
pub const OBS_LEN: usize = OBS_ROWS * OBS_COLS * NUM_CHANNELS;

/// `(rows, cols, channels)` of an observation.
pub type ObsShape = (usize, usize, usize);

/// Plane names in channel order (`observations.CHANNEL_NAMES`).
pub const CHANNEL_NAMES: [&str; NUM_CHANNELS] = [
    "on_board",
    "food",
    "hazard",
    "own_head",
    "own_body",
    "own_countdown",
    "opp_head_ge",
    "opp_head_lt",
    "opp_body",
    "opp_countdown",
    "opp_head_health",
    "own_health",
    "own_length",
];

/// Feature names in column order (`modes.FEATURE_NAMES`).
pub const FEATURE_NAMES: [&str; NUM_FEATURES] = [
    "is_standard",
    "is_duel",
    "is_royale",
    "is_constrictor",
    "turn",
    "shrink_phase",
    "opponents_alive",
];

/// Channel index of each plane (SPEC 3.1).
pub mod ch {
    /// 1 on board cells, 0 in the padding.
    pub const ON_BOARD: usize = 0;
    /// 1 where there is food; always 0 when food is hidden (constrictor).
    pub const FOOD: usize = 1;
    /// The stacked hazard count, not normalised.
    pub const HAZARD: usize = 2;
    /// 1 at the own head (living seat, head on the board).
    pub const OWN_HEAD: usize = 3;
    /// 1 where the own countdown is positive (head included).
    pub const OWN_BODY: usize = 4;
    /// Own countdown `* f32(1/cells)`.
    pub const OWN_COUNTDOWN: usize = 5;
    /// 1 at the head of a living opponent at least as long as the agent.
    pub const OPP_HEAD_GE: usize = 6;
    /// 1 at the head of a living opponent shorter than the agent.
    pub const OPP_HEAD_LT: usize = 7;
    /// 1 where any living opponent's countdown is positive.
    pub const OPP_BODY: usize = 8;
    /// Max living-opponent countdown `* f32(1/cells)`.
    pub const OPP_COUNTDOWN: usize = 9;
    /// At a living opponent's head: its health `* 0.01` (max over coinciding heads).
    pub const OPP_HEAD_HEALTH: usize = 10;
    /// Own health `* 0.01` on every board cell (0 when dead).
    pub const OWN_HEALTH: usize = 11;
    /// Own length `* f32(1/cells)` on every board cell (0 when dead).
    pub const OWN_LENGTH: usize = 12;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn channel_constants_match_names() {
        let idx = [
            (ch::ON_BOARD, "on_board"),
            (ch::FOOD, "food"),
            (ch::HAZARD, "hazard"),
            (ch::OWN_HEAD, "own_head"),
            (ch::OWN_BODY, "own_body"),
            (ch::OWN_COUNTDOWN, "own_countdown"),
            (ch::OPP_HEAD_GE, "opp_head_ge"),
            (ch::OPP_HEAD_LT, "opp_head_lt"),
            (ch::OPP_BODY, "opp_body"),
            (ch::OPP_COUNTDOWN, "opp_countdown"),
            (ch::OPP_HEAD_HEALTH, "opp_head_health"),
            (ch::OWN_HEALTH, "own_health"),
            (ch::OWN_LENGTH, "own_length"),
        ];
        for (i, name) in idx {
            assert_eq!(CHANNEL_NAMES[i], name);
        }
        assert_eq!(OBS_LEN, 5733);
        assert_eq!(FEATURE_NAMES[col::OPPONENTS_ALIVE], "opponents_alive");
    }
}
