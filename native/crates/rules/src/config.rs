//! Constants, moves, elimination causes, rulesets, modes and the game configuration.
//!
//! Ported from `src/slinky/types.py` (constants types.py:29-35, `Cause` types.py:39-60,
//! `Ruleset` types.py:63-80, `GameConfig` types.py:82-115) and `src/slinky/modes.py`
//! (`MODE_NAMES`, `mode_config`, `mode_of`; modes.py:43-121). Only what the az_modes search
//! plays is kept: the standard, constrictor and royale rulesets with 2 to 4 snakes on boards up
//! to 11x11. Map randomness (food spawning, snake placement) is not part of the search and is
//! not ported, so the map is folded into the ruleset the way the server normalises it
//! (server.py:196-222: every royale variant becomes the royale ruleset).

use crate::RulesError;

/// Most snakes a game may have (the search's joint actions are `4^N`).
pub const MAX_SNAKES: usize = 4;
/// Widest supported board.
pub const MAX_WIDTH: usize = 11;
/// Tallest supported board.
pub const MAX_HEIGHT: usize = 11;
/// Cells of the largest board; grids are fixed arrays of this size indexed `y * width + x`.
pub const MAX_CELLS: usize = MAX_WIDTH * MAX_HEIGHT;
/// Length of the royale shrink-side list on the largest board (`W + H - 1`, types.py:154-156).
pub const MAX_SIDES: usize = MAX_WIDTH + MAX_HEIGHT - 1;
/// Moves per snake.
pub const NUM_ACTIONS: usize = 4;
/// Full health (types.py:35).
pub const MAX_HEALTH: i32 = 100;
/// A royale shrink side that moves no edge: the server fills the shrinks it has not seen with it
/// (server.py:115, 237-261).
pub const UNKNOWN_SIDE: i8 = 4;

/// A move. The discriminant is the action id used everywhere (types.py:29-33).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum Move {
    /// `y + 1`.
    Up = 0,
    /// `y - 1`.
    Down = 1,
    /// `x - 1`.
    Left = 2,
    /// `x + 1`.
    Right = 3,
}

impl Move {
    /// All moves in action-id order.
    pub const ALL: [Move; NUM_ACTIONS] = [Move::Up, Move::Down, Move::Left, Move::Right];

    /// The API name (`"up"`, `"down"`, `"left"`, `"right"`).
    pub fn name(self) -> &'static str {
        ["up", "down", "left", "right"][self as usize]
    }

    /// The move with action id `id` (0 to 3), if any.
    pub fn from_index(id: usize) -> Option<Move> {
        Move::ALL.get(id).copied()
    }

    /// `(dx, dy)` of the move (types.py:33).
    pub fn delta(self) -> (i32, i32) {
        DELTAS[self as usize]
    }
}

/// `(dx, dy)` per action id: UP, DOWN, LEFT, RIGHT (types.py:33).
pub const DELTAS: [(i32, i32); NUM_ACTIONS] = [(0, 1), (0, -1), (-1, 0), (1, 0)];

/// Elimination cause codes, as stored in [`GameState::elim_cause`](crate::GameState::elim_cause)
/// (types.py:39-49).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(i8)]
pub enum Cause {
    /// Still alive.
    None = 0,
    /// `"out-of-health"`.
    OutOfHealth = 1,
    /// `"wall-collision"`.
    OutOfBounds = 2,
    /// `"snake-self-collision"`.
    SelfCollision = 3,
    /// `"snake-collision"`.
    Collision = 4,
    /// `"head-collision"`.
    HeadCollision = 5,
    /// `"hazard"`.
    Hazard = 6,
}

impl Cause {
    /// The engine's `EliminatedCause` string (`CAUSE_TO_ENGINE`, types.py:51-59).
    pub fn engine_name(self) -> &'static str {
        match self {
            Cause::None => "",
            Cause::OutOfHealth => "out-of-health",
            Cause::OutOfBounds => "wall-collision",
            Cause::SelfCollision => "snake-self-collision",
            Cause::Collision => "snake-collision",
            Cause::HeadCollision => "head-collision",
            Cause::Hazard => "hazard",
        }
    }

    /// The cause for an engine string (`ENGINE_TO_CAUSE`, types.py:60).
    pub fn from_engine_name(name: &str) -> Option<Cause> {
        [
            Cause::None,
            Cause::OutOfHealth,
            Cause::OutOfBounds,
            Cause::SelfCollision,
            Cause::Collision,
            Cause::HeadCollision,
            Cause::Hazard,
        ]
        .into_iter()
        .find(|c| c.engine_name() == name)
    }

    /// The cause with code `code` (0 to 6), if any.
    pub fn from_code(code: i8) -> Option<Cause> {
        [
            Cause::None,
            Cause::OutOfHealth,
            Cause::OutOfBounds,
            Cause::SelfCollision,
            Cause::Collision,
            Cause::HeadCollision,
            Cause::Hazard,
        ]
        .get(usize::try_from(code).ok()?)
        .copied()
    }
}

/// The rulesets this crate plays (a subset of `types.Ruleset`, types.py:63-80).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Ruleset {
    /// `"standard"`.
    Standard,
    /// `"constrictor"`: no food, full health every turn, growth every turn.
    Constrictor,
    /// `"royale"`: the shrinking hazard zone, regenerated by the rules every turn.
    Royale,
}

impl Ruleset {
    /// The API name.
    pub fn name(self) -> &'static str {
        match self {
            Ruleset::Standard => "standard",
            Ruleset::Constrictor => "constrictor",
            Ruleset::Royale => "royale",
        }
    }

    /// Parse an API ruleset name. Wrapped and solo rulesets are refused.
    pub fn from_name(name: &str) -> Result<Ruleset, RulesError> {
        match name {
            "standard" => Ok(Ruleset::Standard),
            "constrictor" => Ok(Ruleset::Constrictor),
            "royale" => Ok(Ruleset::Royale),
            other => Err(RulesError::Ruleset(other.to_string())),
        }
    }
}

/// The four leaderboard modes, in `modes.MODE_NAMES` order (modes.py:43). The discriminant is the
/// mode id, which indexes the network's one-hot features.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum Mode {
    /// Standard ruleset with 3 or more snakes.
    Standard = 0,
    /// Standard ruleset with exactly 2 snakes.
    Duel = 1,
    /// Royale ruleset (any snake count >= 2).
    Royale = 2,
    /// Constrictor ruleset (any snake count >= 2).
    Constrictor = 3,
}

impl Mode {
    /// All modes in id order (`MODE_NAMES`).
    pub const ALL: [Mode; 4] = [Mode::Standard, Mode::Duel, Mode::Royale, Mode::Constrictor];

    /// The mode name (`"standard"`, `"duel"`, `"royale"`, `"constrictor"`).
    pub fn name(self) -> &'static str {
        ["standard", "duel", "royale", "constrictor"][self as usize]
    }

    /// Parse a mode name.
    pub fn from_name(name: &str) -> Result<Mode, RulesError> {
        Mode::ALL
            .into_iter()
            .find(|m| m.name() == name)
            .ok_or_else(|| RulesError::Mode(format!("unknown game mode {name:?}")))
    }

    /// The default seat count of the mode (`DEFAULT_SNAKES`, modes.py:45).
    pub fn default_snakes(self) -> usize {
        if self == Mode::Duel { 2 } else { 4 }
    }
}

/// Static configuration of a game: board size, seats, ruleset and the settings the rules read.
///
/// Mirrors `types.GameConfig` (types.py:82-115) restricted to what the search uses. The food
/// settings are absent because the search never spawns food (SPEC 4.10). The fields are private
/// so a config is always valid: every grid index derived from it is in range.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct GameConfig {
    width: usize,
    height: usize,
    num_snakes: usize,
    ruleset: Ruleset,
    hazard_damage_per_turn: i32,
    shrink_every_n_turns: i32,
    max_turns: Option<i32>,
}

impl GameConfig {
    /// A config with the Python defaults for everything else: `hazard_damage_per_turn = 14`,
    /// `shrink_every_n_turns = 25`, `max_turns = None` (types.py:91-101).
    ///
    /// Errors on a board outside 1..=11 per side or a seat count outside 2..=4.
    pub fn new(
        width: usize,
        height: usize,
        num_snakes: usize,
        ruleset: Ruleset,
    ) -> Result<GameConfig, RulesError> {
        if !(1..=MAX_WIDTH).contains(&width) || !(1..=MAX_HEIGHT).contains(&height) {
            return Err(RulesError::BoardSize { width, height });
        }
        if !(2..=MAX_SNAKES).contains(&num_snakes) {
            return Err(RulesError::NumSnakes(num_snakes));
        }
        Ok(GameConfig {
            width,
            height,
            num_snakes,
            ruleset,
            hazard_damage_per_turn: 14,
            shrink_every_n_turns: 25,
            max_turns: None,
        })
    }

    /// The 11x11 config of a leaderboard mode (`modes.mode_config`, modes.py:72-92), as the
    /// server's `MODE_CONFIGS` holds them. `num_snakes = None` takes the mode's default (2 for
    /// duel, else 4). A duel must have exactly 2 seats, standard 3 or more.
    pub fn for_mode(mode: Mode, num_snakes: Option<usize>) -> Result<GameConfig, RulesError> {
        let n = num_snakes.unwrap_or(mode.default_snakes());
        if (mode == Mode::Duel && n != 2) || (mode == Mode::Standard && n < 3) || n < 2 {
            return Err(RulesError::Mode(format!(
                "mode {:?} cannot have {n} snakes",
                mode.name()
            )));
        }
        let ruleset = match mode {
            Mode::Standard | Mode::Duel => Ruleset::Standard,
            Mode::Royale => Ruleset::Royale,
            Mode::Constrictor => Ruleset::Constrictor,
        };
        GameConfig::new(MAX_WIDTH, MAX_HEIGHT, n, ruleset)
    }

    /// Set `hazard_damage_per_turn` (any value; the rules clamp it to +-100).
    pub fn with_hazard_damage(mut self, damage: i32) -> GameConfig {
        self.hazard_damage_per_turn = damage;
        self
    }

    /// Set `shrink_every_n_turns` (must be >= 1).
    pub fn with_shrink_every(mut self, turns: i32) -> Result<GameConfig, RulesError> {
        if turns < 1 {
            return Err(RulesError::ShrinkEvery(turns));
        }
        self.shrink_every_n_turns = turns;
        Ok(self)
    }

    /// Set the training-only truncation `max_turns` (`None` at play, server.py:207).
    pub fn with_max_turns(mut self, max_turns: Option<i32>) -> GameConfig {
        self.max_turns = max_turns;
        self
    }

    /// Board width.
    pub fn width(&self) -> usize {
        self.width
    }

    /// Board height.
    pub fn height(&self) -> usize {
        self.height
    }

    /// `width * height`.
    pub fn cells(&self) -> usize {
        self.width * self.height
    }

    /// Number of seats `N` (dead seats included).
    pub fn num_snakes(&self) -> usize {
        self.num_snakes
    }

    /// The ruleset.
    pub fn ruleset(&self) -> Ruleset {
        self.ruleset
    }

    /// Hazard damage per layer and turn, before the rules' clamp to +-100.
    pub fn hazard_damage_per_turn(&self) -> i32 {
        self.hazard_damage_per_turn
    }

    /// Turns between royale shrinks (>= 1).
    pub fn shrink_every_n_turns(&self) -> i32 {
        self.shrink_every_n_turns
    }

    /// Training-only truncation; `None` at play.
    pub fn max_turns(&self) -> Option<i32> {
        self.max_turns
    }

    /// Length of the royale shrink-side list, `W + H - 1` (`royale_num_sides`, types.py:154-156).
    pub fn num_sides(&self) -> usize {
        self.width + self.height - 1
    }

    /// The leaderboard mode this config plays (`modes.mode_of`, modes.py:95-121, after the
    /// server's map normalisation): royale and constrictor by ruleset, standard with 2 seats is a
    /// duel, with more it is standard.
    pub fn mode(&self) -> Mode {
        match self.ruleset {
            Ruleset::Royale => Mode::Royale,
            Ruleset::Constrictor => Mode::Constrictor,
            Ruleset::Standard if self.num_snakes == 2 => Mode::Duel,
            Ruleset::Standard => Mode::Standard,
        }
    }

    /// Whether `(x, y)` lies on the board (`rules.in_bounds`, rules.py:50-53).
    #[inline]
    pub fn in_bounds(&self, x: i32, y: i32) -> bool {
        x >= 0 && y >= 0 && (x as usize) < self.width && (y as usize) < self.height
    }

    /// The grid index `y * width + x` of an on-board point, or `None` off the board.
    #[inline]
    pub fn cell(&self, x: i32, y: i32) -> Option<usize> {
        if self.in_bounds(x, y) {
            Some(y as usize * self.width + x as usize)
        } else {
            None
        }
    }

    /// The `(x, y)` of grid index `cell`.
    #[inline]
    pub fn xy(&self, cell: usize) -> (i32, i32) {
        ((cell % self.width) as i32, (cell / self.width) as i32)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn validates_sizes() {
        assert!(GameConfig::new(11, 11, 4, Ruleset::Standard).is_ok());
        assert!(GameConfig::new(12, 11, 4, Ruleset::Standard).is_err());
        assert!(GameConfig::new(0, 11, 4, Ruleset::Standard).is_err());
        assert_eq!(
            GameConfig::new(11, 11, 5, Ruleset::Standard),
            Err(RulesError::NumSnakes(5))
        );
        assert!(GameConfig::new(11, 11, 1, Ruleset::Standard).is_err());
        let c = GameConfig::new(7, 9, 2, Ruleset::Royale).unwrap();
        assert!(c.with_shrink_every(0).is_err());
        assert_eq!(c.num_sides(), 15);
        assert_eq!(c.cell(6, 8), Some(62));
        assert_eq!(c.xy(62), (6, 8));
        assert_eq!(c.cell(7, 0), None);
        assert_eq!(c.cell(-1, 0), None);
    }

    #[test]
    fn modes_round_trip() {
        for mode in Mode::ALL {
            let c = GameConfig::for_mode(mode, None).unwrap();
            assert_eq!(c.mode(), mode);
            assert_eq!(Mode::from_name(mode.name()), Ok(mode));
        }
        assert!(GameConfig::for_mode(Mode::Duel, Some(3)).is_err());
        assert!(GameConfig::for_mode(Mode::Standard, Some(2)).is_err());
        assert_eq!(
            GameConfig::for_mode(Mode::Royale, Some(2)).unwrap().mode(),
            Mode::Royale
        );
        assert_eq!(
            GameConfig::for_mode(Mode::Standard, Some(3))
                .unwrap()
                .num_snakes(),
            3
        );
    }

    #[test]
    fn causes_and_moves() {
        for code in 0..7 {
            let c = Cause::from_code(code).unwrap();
            assert_eq!(c as i8, code);
            assert_eq!(Cause::from_engine_name(c.engine_name()), Some(c));
        }
        assert_eq!(Cause::from_code(7), None);
        assert_eq!(Cause::from_code(-1), None);
        assert_eq!(Move::from_index(3), Some(Move::Right));
        assert_eq!(Move::Left.delta(), (-1, 0));
        assert_eq!(Ruleset::from_name("wrapped").ok(), None);
    }
}
