//! slinky-rules: the game state and the Battlesnake rules that slinky's `az_modes` search
//! simulates, ported from the JAX code with bit-exact results.
//!
//! Sources (the Python of slinky v0.1.0, `src/slinky/`): `types.py` (state layout, constants),
//! `rules.py` (the step, `rules_step`, and the masks), `mcts.py` (`_transition`, `_legal`,
//! `placement_values`), `modes.py` (modes), `engine_json.py` (building a state from engine
//! snakes). See `native-az/SPEC.md` sections 4.4, 4.6 and 5. Supported: the standard,
//! constrictor and royale rulesets with 2 to 4 snakes on boards up to 11x11, without food
//! spawning (the search never spawns food). Wrapped and solo games, and more than 4 snakes, are
//! refused with a [`RulesError`]. No `unsafe`, no heap allocation per step, and nothing panics on
//! hostile field values.
//!
//! Parity: `tests/golden.rs` replays transitions generated by `native/golden/rules_golden.py`
//! with slinky's jitted rules (all four modes plus 3-snake, 2-snake royale/constrictor,
//! hazard and small-board variants) and requires the full next state, the masks and the
//! placement values to match exactly.
//!
//! # Public API
//!
//! ```
//! use slinky_rules::{Cause, GameConfig, GameState, Mode, Move};
//!
//! // A config: one of the four leaderboard modes on 11x11 ...
//! let cfg = GameConfig::for_mode(Mode::Duel, None)?;           // 2 seats, standard ruleset
//! // ... or any supported game: GameConfig::new(w, h, n, Ruleset::Royale)?
//! //        .with_hazard_damage(14).with_shrink_every(25)?
//! assert_eq!(cfg.mode(), Mode::Duel);
//!
//! // A state, seat by seat, from head-first (x, y) segments (engine_json.state_from_engine).
//! let mut s = GameState::new(&cfg);
//! s.set_snake(&cfg, 0, &[(1, 1), (1, 1), (1, 1)], 100, None)?;     // living, stacked at turn 0
//! s.set_snake(&cfg, 1, &[(9, 9), (9, 8), (9, 7)], 100, None)?;
//! // a padded dead seat would be: s.set_snake(&cfg, 3, &[], 0, Some((Cause::Collision, 0)))?;
//! s.add_food(&cfg, 5, 5)?;
//! s.add_hazard(&cfg, 0, 0);                                     // stacks; off-board dropped
//! s.turn = 0;
//! // royale only: s.sides = shrink sides (0 left, 1 right, 2 bottom, 3 top, UNKNOWN_SIDE = 4)
//! s.refresh_done(&cfg);
//!
//! // What the search reads at a node.
//! let legal = s.legal_moves(&cfg);       // [[bool; 4]; 4]: mask, forced [T,F,F,F] if dead/starving
//! let forced = s.forced(&cfg);           // [bool; 4]: dead or certainly starving
//! let values = s.placement_values(&cfg, -0.5); // [f32; 4]: exact for dead seats / done states
//! assert!(legal[0][0] && !forced[0] && !s.done);
//!
//! // Expanding a joint action (seat 0 = least significant digit in the search's encoding).
//! let child = s.child(&cfg, &[Move::Up as u8, Move::Down as u8, 0, 0]); // turn + 1, done updated
//! assert_eq!(child.turn, 1);
//! # let _ = (values, Cause::None);
//! # Ok::<(), slinky_rules::RulesError>(())
//! ```
//!
//! Types and functions:
//!
//! * [`GameConfig`]: `new(width, height, num_snakes, Ruleset) -> Result`, `for_mode(Mode,
//!   Option<usize>) -> Result`, `with_hazard_damage(i32)`, `with_shrink_every(i32) -> Result`,
//!   `with_max_turns(Option<i32>)`; getters `width()`, `height()`, `cells()`, `num_snakes()`,
//!   `ruleset()`, `hazard_damage_per_turn()`, `shrink_every_n_turns()`, `max_turns()`,
//!   `num_sides()`, `mode() -> Mode`; geometry `in_bounds(x, y)`, `cell(x, y) -> Option<usize>`
//!   (index `y * width + x`), `xy(cell)`.
//! * [`GameState`] (`Copy`, ~1.3 KB, all fields public): `body: [[i16; 121]; 4]` countdown grids,
//!   `head: [[i32; 2]; 4]` (x, y), `length`, `health: [i32; 4]`, `alive: [bool; 4]`,
//!   `last_move: [u8; 4]`, `food: u128` bitboard, `hazard: [i16; 121]` counts, `turn: i32`,
//!   `elim_cause: [i8; 4]` ([`Cause`] codes), `elim_turn: [i32; 4]`, `done: bool`,
//!   `sides: [i8; 21]` (royale). Builders: `new`, `set_snake`, `add_food`, `add_hazard`,
//!   `refresh_done`. Readers: `food_at`, `has_food(cell)`, `hazard_at`, `body_at`, `head_cell`,
//!   `num_alive`, `is_game_over`.
//! * Step: `rules_step(&mut self, cfg, &Actions)` (`rules.rules_step`: no turn increment),
//!   `advance(&mut self, cfg, &Actions)` (the search's `_transition`: also `turn + 1` and `done`),
//!   `child(&self, cfg, &Actions) -> GameState`. [`Actions`] is `[u8; 4]`, one action id per seat;
//!   ids >= 4 repeat `last_move`.
//! * Search queries: `certainly_starving -> [bool; 4]`, `blocked_cells -> u128`,
//!   `action_mask -> MoveMask`, `legal_moves -> MoveMask`, `forced -> [bool; 4]`,
//!   `placement_values(cfg, draw_value) -> [f32; 4]`. [`MoveMask`] is `[[bool; 4]; 4]`.
//! * [`royale_hazards`]`(cfg, &sides, turn) -> [i16; 121]`: the royale zone shown at `turn`.
//! * Enums [`Move`] (`Up`, `Down`, `Left`, `Right`; [`DELTAS`]), [`Cause`] (engine strings),
//!   [`Ruleset`], [`Mode`] (in `MODE_NAMES` order), and [`default_move`] (`_direction`).
//! * Constants: [`MAX_SNAKES`] = 4, [`MAX_WIDTH`] = [`MAX_HEIGHT`] = 11, [`MAX_CELLS`] = 121,
//!   [`MAX_SIDES`] = 21, [`NUM_ACTIONS`] = 4, [`MAX_HEALTH`] = 100, [`UNKNOWN_SIDE`] = 4.
//!
//! Speed (release, one core of the dev box, `examples/bench.rs`): `legal_moves` + `child` take
//! about 130 ns in a duel, 230 ns in standard 4p, 330 ns in royale and 450 ns in constrictor.
//!
//! Seats `>= num_snakes` in the fixed-size arrays are unused: the step leaves them alone and the
//! queries return false / 0 there.

